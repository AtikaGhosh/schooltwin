export const dictionaries = { en, or } satisfies Record<UiLocale, Dictionary>

export function translate(
  locale: UiLocale,
  key: TranslationKey,
  values: Record<string, string | number> = {},
): string {
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    dictionaries[locale][key],
  )
}

export type { TranslationKey }

export function validationMessage(
  locale: UiLocale,
  code:
    | 'students_integer'
    | 'students_range'
    | 'contextual_once'
    | 'invalid_answer'
    | 'operator_required',
  values: Record<string, string | number> = {},
): string {
  const keys = {
    students_integer: 'validation.studentsInteger',
    students_range: 'validation.studentsRange',
    contextual_once: 'validation.contextualOnce',
    invalid_answer: 'validation.invalidAnswer',
    operator_required: 'validation.operatorRequired',
  } as const
  return translate(locale, keys[code], values)
}
